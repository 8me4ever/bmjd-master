def series_neighbors(job, by_series):
    """同职责系列的其他岗位（作为层级连续性/身份一致性证据）。"""
    return [x for x in by_series.get(job['series_id'], []) if x['job_id'] != job['job_id']]



def judge(job, by_series):
    """核心判定：岗位A的名称 与 岗位A的现有JD(本岗原文) 是否匹配。

    返回 (verdict, reasons, score)
      verdict='匹配'          -> 直接略过，保留本岗JD不动
      verdict='不匹配-需重写'   -> 按名称重写，压到4-5条
      verdict='存疑-已标注'    -> 不足以判定矛盾，保留原JD，仅标注供Codex复核
    """
    # 比对对象是本岗自己的原文（current_jd 即由这些原文整理而来）
    text = ''.join(B.src_text(s) for s in job['source_ids'][:3])
    name = job['baseline_name']
    k = NORM(text)
    score = B.name_match_score(name, text)
    kws = func_keywords(job['function_name'], name)
    kws += FUNC_KW.get(job['function_name'], [])
    hits = [w for w in kws if NORM(w) and NORM(w) in k]

    # 1 名称核心词直接出现在本岗JD中
    if score >= 0.5:
        return '匹配', ['岗位名核心词在本岗JD中命中率%.2f' % score], score

    # 2 本岗JD含本职能核心词：讨论的是本类岗位事务
    if len(hits) >= 1:
        return '匹配', ['本岗JD含本职能/本岗核心词：%s' % '、'.join(hits[:4])], score

    # 2a 岗位名与JD同期出现同一专业对象（模糊语义对应，不依赖全文分词）
    sem = _sem_link(name, text, job['function_name'])
    if sem:
        return '匹配', ['岗位名与JD共同指向：%s' % '、'.join(sem[:3])], score

    # 2b 语域外的专业对象：JD通篇是另一个具体专业/设备体系（如"影音领班"写汽车零部件开发）
    off = _off_domain(name, job['function_name'], text) if score < 0.5 else []
    if off and not hits:
        return '不匹配-需重写', ['岗位名“%s”，但本岗JD通篇为“%s”领域内容' % (name, '、'.join(off[:3]))], score

    # 3 本岗JD整体属其他职务族（名称与职责实质矛盾：简称/英文缩写 + 完全不同领域）
    for pat_name, pat_body in ROLE_CONFLICT:
        if re.search(pat_name, name) and re.search(pat_body, text):
            return '不匹配-需重写', ['岗位名“%s”，本岗JD主体为“%s”，属不同职务族' % (
                re.search(pat_name, name).group(), re.search(pat_body, text).group())], score

    # 4 其余：名称命中率低但JD仍围绕本职能业务（简称、英文缩写、专有名词等），
    #    按最小化原则保留原JD，仅标注，不推翻
    return '存疑-已标注', ['名称命中率%.2f，JD未出现跨领域错位，按现有JD保留' % score], score


