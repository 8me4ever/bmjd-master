def func_keywords(function_name, name):
    """本职能关键词：职能名 + 岗位名拆出的有意义的职务/对象词。
    必须按词而不是按整个名称取，否则"FAE现场应用工程师"会被当成一个长串，永远命中不了。"""
    kws = []
    if function_name and len(function_name) >= 2:
        kws.append(function_name)
    parts = []
    for part in re.split(r'[/／、,，（）()]', name):
        part = part.strip()
        # 英文缩写优先单列（FAE、CAD、HRIS 等是岗位实质词）
        parts += re.findall(r'[A-Za-z]{2,}', part)
        part = re.sub(r'(高级|中级|初级|资深|首席|助理|见习|实习|储备|副|正|师|员|工|岗)$', '', part)
        if len(part) >= 2:
            parts.append(part)
    # 中文名称再切出 2-4 字词组；英文缩写单独成词
    for p in list(parts):
        if re.search(r'[\u4e00-\u9fff]', p):
            for seg in re.findall(r'[\u4e00-\u9fff]{2,}', p):
                for n in (4, 3, 2):
                    for i in range(0, max(1, len(seg) - n + 1)):
                        w = seg[i:i + n]
                        if len(w) == n and w not in STOP_W:
                            parts.append(w)
                break
        else:
            parts.append(p)
    kws += [p for p in parts if len(p) >= 2]
    return list(dict.fromkeys(kws))


# 通用职务尾巴，不作为职能关键词（否则任何岗位都会"命中"）
