def _off_domain(name, function_name, text):
    """JD 通篇属于另一个具体专业体系，且岗位名与职能都不涉及。至少命中两处才判。"""
    own = name + function_name
    ok = FUNC_DOMAIN_OK.get(function_name, set())
    found = []
    for dom, words in DOMAIN_GROUPS.items():
        if dom in ok:
            continue
        if any(w in own for w in words):
            continue
        if sum(1 for w in words if w in text) >= 2:
            found.append(dom)
    return found


